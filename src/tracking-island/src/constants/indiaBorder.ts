/**
 * Mounts an inverse-polygon mask that covers all territory outside of India
 * and highlights the official Indian national boundary with a precision border.
 */
export function addIndiaBoundaryMask(map: L.Map): L.Polygon {
  if (!map.getPane('indiaMaskPane')) {
    map.createPane('indiaMaskPane');
    const maskPane = map.getPane('indiaMaskPane');
    if (maskPane) {
      maskPane.style.zIndex = '250'; // Sits above base tiles (200) and below overlays (400) / markers (600)
      maskPane.style.pointerEvents = 'none';
    }
  }

  const mask = L.polygon([WORLD_MASK_OUTER_RING, INDIA_BORDER_COORDS], {
    pane: 'indiaMaskPane',
    color: '#2563eb',
    weight: 2,
    opacity: 0.95,
    fillColor: '#0b1329',
    fillOpacity: 0.70,
    interactive: false,
    className: 'ti-india-mask',
  });
  mask.addTo(map);
  return mask;
}

