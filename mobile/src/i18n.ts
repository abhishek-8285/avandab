let currentLocale: SupportedLocale = 'en';

export const setLocale = (locale: SupportedLocale) => {
  currentLocale = locale;
};

export const getLocale = (): SupportedLocale => currentLocale;

export const t = (key: string, fallback?: string, localeOverride?: SupportedLocale): string => {
  const activeLocale = localeOverride || currentLocale;
  const translation = DICTIONARY[activeLocale]?.[key];
  if (translation) return translation;

  const enFallback = DICTIONARY.en?.[key];
  if (enFallback) return enFallback;

  return fallback || key;
};
